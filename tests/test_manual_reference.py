import hashlib
import json
from pathlib import Path

import pytest

from lechonk.adapter.manual_reference import (
    AUTHORITY,
    ManualReferenceError,
    load_manual_reference,
    parse_mediawiki,
    render_search,
    search_entries,
)
from lechonk.adapter.classic_reference import PINNED_IMAGE_REF


WIKI = """<!-- Generated by freeciv-manual version test -->
=Freeciv test unit types help (Classic ruleset)=
===Settlers===
<!-- cost -->
Cost: 40 shields
<!-- helptext -->
* Can do the action '''Build City'''.
===Warriors===
Cost: 10 shields
<table><tr><td>[[Image:u.warriors.png]]</td><td>Warriors</td><td>1/1</td></tr></table>
"""


def test_mediawiki_parser_keeps_context_and_strips_markup():
    entries = parse_mediawiki(WIKI, source_file="classic7.mediawiki")
    settlers = next(e for e in entries if e.name == "Settlers")
    assert settlers.category == "unit"
    assert settlers.section.startswith("Freeciv test")
    assert "Build City" in settlers.text
    assert "'''" not in settlers.text
    assert all("<" not in e.text for e in entries)


def test_loader_verifies_manifest_and_searches_naturally(tmp_path: Path):
    (tmp_path / "classic7.mediawiki").write_text(WIKI, encoding="utf-8")
    digest = hashlib.sha256(WIKI.encode()).hexdigest()
    (tmp_path / "manual_reference.json").write_text(json.dumps({
        "schema_version": "freeciv-manual-reference-v1", "image_ref": PINNED_IMAGE_REF,
        "image_version": "3.2.91-dev", "ruleset": "classic",
        "manual_files": {"classic7.mediawiki": digest},
    }), encoding="utf-8")
    ref = load_manual_reference(tmp_path)
    assert ref.status == "available"
    assert ref.image_ref == PINNED_IMAGE_REF
    assert search_entries(ref, "what can settlers build")[0]["name"] == "Settlers"
    result = render_search(ref, "warriors", max_chars=10000)
    assert result["authority"] == AUTHORITY
    assert result["entries"][0]["category"] == "unit"


def test_loader_fails_closed_on_stale_checksum(tmp_path: Path):
    path = tmp_path / "classic7.mediawiki"
    path.write_text(WIKI, encoding="utf-8")
    (tmp_path / "reference.json").write_text(json.dumps({"manual_files": {path.name: "0" * 64}}), encoding="utf-8")
    with pytest.raises(ManualReferenceError):
        load_manual_reference(tmp_path)


def test_loader_rejects_wrong_but_well_formed_image_digest(tmp_path: Path):
    path = tmp_path / "classic7.mediawiki"
    path.write_text(WIKI, encoding="utf-8")
    (tmp_path / "reference.json").write_text(json.dumps({
        "schema_version": "freeciv-manual-reference-v1", "ruleset": "classic",
        "image_ref": "civrealm/freeciv-web@sha256:" + "b" * 64,
        "manual_files": {path.name: hashlib.sha256(WIKI.encode()).hexdigest()},
    }), encoding="utf-8")
    with pytest.raises(ManualReferenceError):
        load_manual_reference(tmp_path)


def test_loader_rejects_symlink(tmp_path: Path):
    target = tmp_path / "outside.mediawiki"
    target.write_text(WIKI, encoding="utf-8")
    link = tmp_path / "classic7.mediawiki"
    link.symlink_to(target)
    digest = hashlib.sha256(WIKI.encode()).hexdigest()
    (tmp_path / "reference.json").write_text(json.dumps({"manual_files": {link.name: digest}}), encoding="utf-8")
    with pytest.raises(ManualReferenceError):
        load_manual_reference(tmp_path)


def test_missing_reference_is_explicitly_unavailable(tmp_path: Path):
    ref = load_manual_reference(tmp_path)
    assert ref.status == "unavailable"
    assert ref.entries == ()


def test_generated_classic_manual_when_extracted():
    root = Path("artifacts/reference/freeciv-manual")
    if not root.is_dir():
        pytest.skip("generated Freeciv manual is not present")
    ref = load_manual_reference(root)
    assert len(ref.entries) >= 400
    assert search_entries(ref, "warrior")[0]["name"] == "Warriors"
    assert search_entries(ref, "grassland", categories=("terrain",))[0]["name"] == "Grassland"
    assert search_entries(ref, "warrior", categories=("units",))[0]["name"] == "Warriors"
